  processMemory: async () => {
    const out = {};
    try { Object.assign(out, await process.getProcessMemoryInfo()); } catch {}
    try { const b = process.getBlinkMemoryInfo(); out.blinkKb = b.allocated || 0; } catch {}
    try { const h = process.getHeapStatistics(); out.v8Kb = h.usedHeapSize || 0; } catch {}
    return Object.keys(out).length ? out : null;
  },
